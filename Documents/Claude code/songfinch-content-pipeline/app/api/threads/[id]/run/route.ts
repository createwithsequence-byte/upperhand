export const maxDuration = 300;

// Quality thresholds
const READY_THRESHOLD = 8; // Score ≥ 8 = ship-ready
const POLISH_THRESHOLD = 6; // Score ≥ 6 = needs polish, but salvageable
const REDRAFT_MAX_ATTEMPTS = 2; // Up to 2 redraft attempts on top of initial
const CONVERGENCE_MIN_DELTA = 1.0; // Stop redrafting if improvement < 1.0
const MIN_GEO_POTENTIAL = 6; // Pre-filter article ideas below this
const GENERATE_OVERAGE = 1.5; // Ask for 50% more ideas than target, then filter

/**
 * Thread orchestrator — assembly line v2 with smart redraft loop.
 *
 * Pipeline:
 *   1. Generate (count × 1.5) article ideas, pre-filter by geo_potential
 *   2. For each surviving article (parallel):
 *      a. SEO + GEO research (parallel, ONCE per article)
 *      b. Draft v1 with FULL research context
 *      c. Deterministic banned-phrase gate (free)
 *      d. LLM QA judgment
 *      e. If score < POLISH_THRESHOLD, redraft up to REDRAFT_MAX_ATTEMPTS times
 *         passing QA feedback as input
 *      f. Convergence check between attempts
 *      g. Structure extraction ONLY on the winning version
 *   3. Return summary by bucket (ready / polish / redraft / failed)
 *
 * Cost optimizations baked in:
 *   - Static prompt content (voice rules, references) goes first → Gemini
 *     implicit cache hits across articles
 *   - Research data shared between research → draft → redraft (no re-fetch)
 *   - Structure extraction deferred to final version only
 *   - Convergence check stops doomed redraft loops early
 *   - geo_potential pre-filter avoids drafting bad article ideas
 */
export async function POST(req: Request, context: { params: { id: string } }) {
  const threadId = context.params.id;
  try {
    const body = await req.json().catch(() => ({}));
    const targetCount: number = typeof body.count === "number" ? body.count : 6;
    const ideasToGenerate = Math.ceil(targetCount * GENERATE_OVERAGE);

    const supabase = getSupabase();

    const [threadRes, brandRes, referencesRes] = await Promise.all([
      supabase.from("threads").select("*").eq("id", threadId).maybeSingle(),
      supabase.from("brand").select("*").limit(1).maybeSingle(),
      supabase.from("reference_examples").select("*"),
    ]);

    if (threadRes.error || !threadRes.data) {
      return NextResponse.json({ error: "Thread not found" }, { status: 404 });
    }
    if (brandRes.error || !brandRes.data) {
      return NextResponse.json(
        { error: "Brand not configured" },
        { status: 400 },
      );
    }

    const thread = threadRes.data as Thread;
    const brand = brandRes.data as Brand;
    const references = (referencesRes.data as ReferenceExample[]) ?? [];
    // The thread's keyword universe — generated by /api/agents/seo/expand-keywords.
    // Used to inform draft prompts. Null if never run; agents degrade gracefully.
    const keywordUniverse = thread.keyword_research as {
      keywords?: Array<{
        keyword: string;
        volume_tier: string;
        intent: string;
      }>;
    } | null;

    // ---- STAGE 1: Generate ideas + pre-filter ----
    const batchId = randomUUID();
    const ideas = await trackAgentRun(
      {
        agent: "generate-articles",
        threadId,
        model: "gemini-2.5-flash",
      },
      async () => ({
        value: await generateArticles({
          brand,
          thread,
          count: ideasToGenerate,
        }),
      }),
    );

    // Pre-filter: drop ideas with low geo_potential, keep top targetCount.
    // generate-articles already scores each idea 1-10 on GEO potential — use
    // that signal cheaply BEFORE we burn money researching + drafting them.
    const filteredIdeas = ideas
      .filter((i) => (i.geo_potential ?? 0) >= MIN_GEO_POTENTIAL)
      .sort((a, b) => (b.geo_potential ?? 0) - (a.geo_potential ?? 0))
      .slice(0, targetCount);

    if (filteredIdeas.length === 0) {
      return NextResponse.json({
        ok: true,
        threadId,
        batchId,
        articleCount: 0,
        ready: 0,
        polish: 0,
        redraft: 0,
        failed: 0,
        articles: [],
        message:
          "No article ideas passed the geo_potential filter. Try a different thread.",
      });
    }

    const ideaRows = filteredIdeas.map((idea, i) => ({
      thread_id: threadId,
      ...idea,
      score: idea.geo_potential,
      rank: i + 1,
      status: "approved" as const,
      approved_at: new Date().toISOString(),
      generation_batch: batchId,
    }));

    const { data: inserted, error: insertErr } = await supabase
      .from("articles")
      .insert(ideaRows)
      .select("*");
    if (insertErr || !inserted) {
      return NextResponse.json(
        { error: insertErr?.message ?? "Article insert failed" },
        { status: 500 },
      );
    }

    const articles = inserted as Article[];

    // ---- STAGE 2: Process each article in parallel ----
    const results = await Promise.allSettled(
      articles.map((article) =>
        processOneArticle({
          brand,
          thread,
          article,
          references,
          keywordUniverse,
          supabase,
        }),
      ),
    );

    const summary = results.map((r, i) => {
      const article = articles[i];
      if (r.status === "fulfilled") {
        return { id: article.id, title: article.title, ...r.value };
      }
      return {
        id: article.id,
        title: article.title,
        ok: false,
        error: r.reason instanceof Error ? r.reason.message : String(r.reason),
      };
    });

    revalidatePath(`/threads/${threadId}`);
    revalidatePath("/");

    return NextResponse.json({
      ok: true,
      threadId,
      batchId,
      articleCount: articles.length,
      filteredOut: ideas.length - filteredIdeas.length,
      ready: summary.filter(
        (s) => s.score != null && s.score >= READY_THRESHOLD,
      ).length,
      polish: summary.filter(
        (s) =>
          s.score != null &&
          s.score >= POLISH_THRESHOLD &&
          s.score < READY_THRESHOLD,
      ).length,
      redraft: summary.filter(
        (s) => s.score != null && s.score < POLISH_THRESHOLD,
      ).length,
      failed: summary.filter((s) => !s.ok).length,
      articles: summary,
    });
  } catch (err) {
    return agentErrorResponse("thread-run", err);
  }
}

/**
 * Per-article processor with smart redraft loop.
 *
 * Returns { ok, score?, attempts?, error? }
 *   - score: the final QA score (after any redraft iterations)
 *   - attempts: how many drafts were generated (1-3)
 */
async function processOneArticle({
  brand,
  thread,
  article,
  references,
  keywordUniverse,
  supabase,
}: {
  brand: Brand;
  thread: Thread;
  article: Article;
  references: ReferenceExample[];
  keywordUniverse: {
    keywords?: Array<{ keyword: string; volume_tier: string; intent: string }>;
  } | null;
  supabase: ReturnType<typeof getSupabase>;
}): Promise<{
  ok: boolean;
  score?: number;
  attempts?: number;
  error?: string;
}> {
  try {
    // ---- 2a. Research (SEO + GEO in parallel, ONCE per article) ----
    const [seo, geo] = await Promise.all([
      trackAgentRun(
        {
          agent: "research-seo",
          articleId: article.id,
          threadId: thread.id,
          model: "gemini-2.5-flash",
        },
        async () => ({ value: await researchSeo({ brand, thread, article }) }),
      ),
      trackAgentRun(
        {
          agent: "research-geo",
          articleId: article.id,
          threadId: thread.id,
          model: "gemini-2.5-flash",
        },
        async () => ({
          value: await researchArticleGeo({ brand, thread, article }),
        }),
      ),
    ]);

    // Persist research to dedicated tables. The draft prompt reads from
    // these in-memory results directly; the DB writes are for the workspace
    // UI to render later.
    const seoRow: SeoResearchRow = {
      article_id: article.id,
      serp_top10: seo.serp_analysis.top_results,
      serp_features: seo.serp_analysis.serp_features,
      search_intent: seo.serp_analysis.intent_classification,
      search_volume_estimate: seo.search_volume_estimate,
      keyword_difficulty: seo.keyword_difficulty,
      volume_tier: seo.volume_tier,
      ranking_strategy: seo.ranking_strategy,
      researched_at: new Date().toISOString(),
    };
    const geoRow: GeoResearchRow = {
      article_id: article.id,
      target_prompts: geo.target_prompts,
      target_llms: ["chatgpt", "perplexity", "gemini", "claude"],
      citation_strategy: geo.citation_strategy,
      competitor_citations: geo.competitor_citations,
      researched_at: new Date().toISOString(),
      citation_checklist: null,
    };
    await Promise.all([
      supabase
        .from("seo_research")
        .upsert(seoRow, { onConflict: "article_id" }),
      supabase
        .from("geo_research")
        .upsert(geoRow, { onConflict: "article_id" }),
    ]);

    await supabase
      .from("articles")
      .update({ status: "drafting" })
      .eq("id", article.id);

    // ---- 2b. Draft v1 with full research context ----
    const v1 = await drainAutoDraft({
      brand,
      thread,
      article,
      references,
      seo: seoRow,
      geo: geoRow,
      keywordUniverse,
    });
    if (!v1.text) {
      throw new Error("Auto-draft produced no text");
    }

    // Save v1 immediately so progress is visible even if QA fails
    const v1Save = await saveDraftVersion({
      articleId: article.id,
      markdown: v1.text,
      schemaJson: null,
      socialCuts: null,
      agent: "auto-draft",
      promptHash: v1.promptHash,
    });
    if (!v1Save.ok) throw new Error(v1Save.error);

    // ---- 2c. Deterministic + LLM QA on v1 ----
    let articleWithDraft: Article = { ...article, markdown: v1.text };
    let bestText = v1.text;
    let bestQa: QaResult = await trackAgentRun(
      {
        agent: "run-qa",
        articleId: article.id,
        threadId: thread.id,
        model: "gemini-2.5-flash",
      },
      async () => ({
        value: await withRetry(
          () => runQa({ brand, article: articleWithDraft, references }),
          { tries: 2, backoffMs: 4000 },
        ),
      }),
    );
    await patchDraftQa(article.id, v1Save.version, bestQa).catch(() => {});

    let attempts = 1;
    let lastVersion = v1Save.version;

    // ---- 2d. Redraft loop with convergence check ----
    while (
      bestQa.score < POLISH_THRESHOLD &&
      attempts <= REDRAFT_MAX_ATTEMPTS
    ) {
      // Deterministic pre-check — if the previous draft has hard banned
      // phrases the regex caught them already; the redraft prompt will
      // include them as explicit exclusions. No new info needed.

      const v2 = await trackAgentRun(
        {
          agent: "redraft",
          articleId: article.id,
          threadId: thread.id,
          model: "gemini-2.5-flash",
          metadata: { attempt: attempts + 1 },
        },
        async () => ({
          value: await withRetry(
            () =>
              redraft({
                brand,
                article,
                references,
                previousDraft: bestText,
                previousQa: bestQa,
              }),
            { tries: 2, backoffMs: 4000 },
          ),
        }),
      );

      const v2Save = await saveDraftVersion({
        articleId: article.id,
        markdown: v2.text,
        schemaJson: null,
        socialCuts: null,
        agent: "auto-draft",
        promptHash: v2.promptHash,
      });
      if (!v2Save.ok) {
        console.warn("[thread-run] redraft save failed", v2Save.error);
        break;
      }

      articleWithDraft = { ...article, markdown: v2.text };
      const v2Qa = await trackAgentRun(
        {
          agent: "run-qa",
          articleId: article.id,
          threadId: thread.id,
          model: "gemini-2.5-flash",
          metadata: { attempt: attempts + 1 },
        },
        async () => ({
          value: await withRetry(
            () => runQa({ brand, article: articleWithDraft, references }),
            { tries: 2, backoffMs: 4000 },
          ),
        }),
      );
      await patchDraftQa(article.id, v2Save.version, v2Qa).catch(() => {});

      const delta = v2Qa.score - bestQa.score;
      attempts++;

      if (v2Qa.score > bestQa.score) {
        // Improvement — keep v2 as the new best
        bestText = v2.text;
        bestQa = v2Qa;
        lastVersion = v2Save.version;
      }
      // Convergence check: if we didn't improve by at least CONVERGENCE_MIN_DELTA,
      // stop. The model has hit its ceiling for this article — more attempts
      // just burn budget.
      if (delta < CONVERGENCE_MIN_DELTA) {
        break;
      }
    }

    // ---- 2e. Structure extraction (ONLY on winning version) ----
    // Best-effort. Failure here doesn't sink the article — the markdown is
    // already saved.
    let schemaJson: Record<string, unknown> | null = null;
    let socialCuts: {
      linkedin: string;
      twitter: string;
      instagram: string;
    } | null = null;
    try {
      const structured = await withRetry(
        () =>
          extractDraftStructure({
            brand,
            article,
            brief: {
              title_options: [article.title],
              meta_description: bestText.slice(0, 155),
              h1: article.title,
              h2_outline: [],
              direct_answer: bestText.split("\n\n")[0] ?? "",
              faq: [],
              human_input_slots: [],
              schema_recommendation: "Article + FAQPage",
              internal_links: [],
              social_cuts: { linkedin: "", twitter: "", instagram: "" },
            },
            markdown: bestText,
          }),
        { tries: 2, backoffMs: 4000 },
      );
      schemaJson = structured.schema_json;
      socialCuts = structured.social_cuts;
    } catch {
      // Skip — schema/social can be regenerated on-demand later
    }

    // Mirror the winning draft to articles.markdown so the workspace renders
    // it. Also update qa_result + status + structure data.
    const nextStatus =
      bestQa.score >= READY_THRESHOLD ? "ready_for_review" : "ready_for_qa";
    await supabase
      .from("articles")
      .update({
        markdown: bestText,
        schema_json: schemaJson,
        social_cuts: socialCuts,
        qa_result: bestQa,
        status: nextStatus,
      })
      .eq("id", article.id);

    // Patch the winning version's draft row with the structure data too,
    // so article_drafts history is complete.
    if (schemaJson || socialCuts) {
      await supabase
        .from("article_drafts")
        .update({ schema_json: schemaJson, social_cuts: socialCuts })
        .eq("article_id", article.id)
        .eq("version", lastVersion)
        .catch(() => {});
    }

    return { ok: true, score: bestQa.score, attempts };
  } catch (err) {
    return {
      ok: false,
      error: err instanceof Error ? err.message : String(err),
    };
  }
}

/**
 * Run streamAutoDraft and drain its text stream into a string. Used in
 * orchestrator context where we don't have an HTTP response to pipe to.
 */
async function drainAutoDraft(
  params: Parameters<typeof streamAutoDraft>[0],
): Promise<{ text: string; promptHash: string }> {
  let capturedText = "";
  let capturedHash = "";
  const stream = streamAutoDraft({
    ...params,
    onFinish: async ({ text, promptHash }) => {
      capturedText = text;
      capturedHash = promptHash;
    },
  });
  // Drain the underlying response body until the stream completes (which
  // also fires onFinish).
  const reader = stream.toTextStreamResponse().body?.getReader();
  if (reader) {
    while (true) {
      const { done } = await reader.read();
      if (done) break;
    }
  }
  // Deterministic banned-phrase pre-check is also available here if needed,
  // but the run-qa agent already runs it as Phase 1.
  void findBannedPhrases;
  return { text: capturedText, promptHash: capturedHash };
}
